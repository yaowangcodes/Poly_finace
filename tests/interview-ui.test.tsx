it("keeps typed text on a failed save so a user can retry", async () => {
  const state = createInterview();
  const fetchMock = vi.fn().mockResolvedValueOnce({ ok: true, json: async () => ({ state, version: 0, mode: "guided" }) }).mockResolvedValueOnce({ ok: false, json: async () => ({ error: "Save failed" }) });
  vi.stubGlobal("fetch", fetchMock);
  render(<InterviewApp />);
  await userEvent.click(await screen.findByRole("button", { name: "Answer in my own words" }));
  await userEvent.type(screen.getByRole("textbox", { name: /Your answer/ }), "Saving for a house");
  await userEvent.click(screen.getByRole("button", { name: "Continue" }));
  expect(await screen.findByRole("alert")).toHaveTextContent("Save failed");
  expect(screen.getByRole("textbox", { name: /Your answer/ })).toHaveValue("Saving for a house");
});
it("highlights a conflicting button answer and its follow-up with evidence and clears after resolution", async () => {
  const { applyPatch, refresh } = await import("@/lib/interview/engine");
  const before = applyPatch(createInterview(), { objective: "growth" });
  const conflicted = answerChoice(structuredClone(before), ["1–3 years · use 2"]);
  const resolved = answerChoice(structuredClone(conflicted), ["Prioritize protecting money for that date"]);
  refresh(resolved);
  vi.stubGlobal("fetch", vi.fn().mockResolvedValueOnce({ ok: true, json: async () => ({ state: before, version: 0, mode: "guided" }) }).mockResolvedValueOnce({ ok: true, json: async () => ({ state: conflicted, version: 1, mode: "guided" }) }).mockResolvedValueOnce({ ok: true, json: async () => ({ state: resolved, version: 2, mode: "guided" }) }));
  const { container } = render(<InterviewApp />);
  await userEvent.click(await screen.findByRole("button", { name: "1–3 years · use 2" }));
  await userEvent.click(screen.getByRole("button", { name: "Continue" }));
  expect(await screen.findByText("Preferences conflict")).toBeInTheDocument();
  expect(screen.getByText("Grow the investment")).toBeInTheDocument();
  expect(screen.getByRole("heading", { name: "Which matters more: your withdrawal date or long-term growth?" })).toBeInTheDocument();
  expect(container.querySelector(".interview-explanation")).not.toHaveAttribute("open");
  expect(screen.getByText("Within 2 years")).toBeInTheDocument();
  expect(screen.getAllByText("AI clarification")).toHaveLength(1);
  expect(container.querySelectorAll("#interview-ai-clarification")).toHaveLength(1);
  expect(container.querySelector(".interview-last-answer--conflict")).not.toBeInTheDocument();
  expect(screen.queryByText(/Some of your preferences conflict/)).not.toBeInTheDocument();
  expect(screen.queryByText(/This response needs to be reconciled/)).not.toBeInTheDocument();
  expect(container.querySelector(".interview-question--conflict")).toBeInTheDocument();
  await userEvent.click(screen.getByRole("button", { name: "Prioritize protecting money for that date" }));
  await userEvent.click(screen.getByRole("button", { name: "Continue" }));
  await waitFor(() => expect(container.querySelector(".interview-question--conflict")).not.toBeInTheDocument());
  expect(container.querySelector(".interview-last-answer--conflict")).not.toBeInTheDocument();
});
